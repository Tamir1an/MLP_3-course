TOKEN_RE = re.compile(r"(?iu)\b[а-яё]+(?:-[а-яё]+)?\b")


def normalize_glued_text(text: str) -> str:
    """Нормализует Unicode и восстанавливает очевидные пропущенные пробелы."""
    text = unicodedata.normalize("NFKC", str(text))
    text = re.sub(r"https?://\S+|www\.\S+", " ", text)
    text = re.sub(r"([а-яё])([А-ЯЁ])", r"\1 \2", text)
    text = re.sub(r"([A-Za-zА-Яа-яЁё])([0-9])", r"\1 \2", text)
    text = re.sub(r"([0-9])([A-Za-zА-Яа-яЁё])", r"\1 \2", text)
    text = re.sub(r"(?<=[.!?,;:])(?=[A-Za-zА-Яа-яЁё])", " ", text)
    text = re.sub(r"([!?.,])\1+", r"\1", text)
    text = re.sub(r"(.)\1{2,}", r"\1\1", text)
    return re.sub(r"\s+", " ", text).strip().lower()


def preprocess_text(text: str, remove_stopwords: bool = True) -> dict:
    """Полный пайплайн: нормализация, токенизация и фильтрация стоп-слов."""
    normalized = normalize_glued_text(text)
    tokens = TOKEN_RE.findall(normalized)
    if remove_stopwords:
        tokens = [token for token in tokens if token not in RUSSIAN_STOPWORDS]
    return {
        "normalized_text": normalized,
        "tokens": tokens,
        "clean_text": " ".join(tokens),
    }

